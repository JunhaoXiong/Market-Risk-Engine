"""Phase 1 pipeline: data -> quality checks -> portfolio returns -> static VaR / ES.

Usage:  python scripts/run_phase1.py [--refresh]

The full-sample VaR here is an *in-sample, descriptive* statistic of the
historical P&L distribution. It is not an out-of-sample forecast; forecasting
and backtesting with rolling windows come in Phase 3.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd
from scipy import stats

from mre.config import PROJECT_ROOT, load_config
from mre.data.loader import get_prices, metadata_path
from mre.data.quality import align_prices, check_prices
from mre.portfolio import pnl, portfolio_returns, simple_returns
from mre.risk.var import risk_table


def describe(r: pd.Series) -> dict:
    return {
        "observations": int(r.size),
        "mean_daily": float(r.mean()),
        "vol_daily": float(r.std(ddof=1)),
        "vol_annualised": float(r.std(ddof=1) * 252 ** 0.5),
        "skewness": float(stats.skew(r)),
        "excess_kurtosis": float(stats.kurtosis(r)),
        "worst_day": float(r.min()),
        "worst_day_date": r.idxmin().date().isoformat(),
        "best_day": float(r.max()),
        "best_day_date": r.idxmax().date().isoformat(),
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--refresh", action="store_true", help="re-download instead of using the cache")
    args = ap.parse_args()

    cfg = load_config()
    prices = get_prices(cfg.tickers, cfg.start, cfg.end, cfg.cache_path, cfg.auto_adjust, args.refresh)
    meta = json.loads(metadata_path(cfg.cache_path).read_text())

    qrep = check_prices(prices, cfg.stale_run_days, cfg.extreme_return_abs, cfg.max_calendar_gap_days)
    if not qrep.passed:
        print(qrep.to_markdown())
        raise SystemExit("Data quality check FAILED; fix the data before computing risk.")

    clean = align_prices(prices)
    asset_r = simple_returns(clean)
    port_r = portfolio_returns(asset_r, cfg.weights)
    port_pnl = pnl(port_r, cfg.portfolio_value)

    tbl = risk_table(port_pnl, cfg.confidence_levels, cfg.quantile_method, cfg.normal_include_mean)
    tbl["var_pct"] = tbl["var"] / cfg.portfolio_value
    tbl["es_pct"] = tbl["es"] / cfg.portfolio_value

    # Empirical exceedance rate of each in-sample VaR (sanity check, not a backtest)
    tbl["in_sample_exceed_rate"] = [
        float((port_pnl < -v).mean()) for v in tbl["var"]
    ]

    desc = describe(port_r)
    asset_desc = pd.DataFrame({t: describe(asset_r[t]) for t in cfg.tickers}).T

    out_dir = PROJECT_ROOT / "reports"
    out_dir.mkdir(exist_ok=True)
    tbl.to_csv(out_dir / "phase1_risk_table.csv", index=False)

    fmt_tbl = tbl.assign(
        alpha=tbl["alpha"].map("{:.0%}".format),
        var=tbl["var"].map("${:,.0f}".format),
        es=tbl["es"].map("${:,.0f}".format),
        var_pct=tbl["var_pct"].map("{:.2%}".format),
        es_pct=tbl["es_pct"].map("{:.2%}".format),
        es_to_var=tbl["es_to_var"].map("{:.2f}".format),
        in_sample_exceed_rate=tbl["in_sample_exceed_rate"].map("{:.2%}".format),
    )
    asset_fmt = asset_desc[["vol_annualised", "skewness", "excess_kurtosis", "worst_day", "worst_day_date"]].copy()
    asset_fmt["vol_annualised"] = asset_fmt["vol_annualised"].map("{:.1%}".format)
    asset_fmt["skewness"] = asset_fmt["skewness"].map("{:.2f}".format)
    asset_fmt["excess_kurtosis"] = asset_fmt["excess_kurtosis"].map("{:.1f}".format)
    asset_fmt["worst_day"] = asset_fmt["worst_day"].map("{:.2%}".format)

    report = f"""# Phase 1 Report: Static 1-day VaR / ES

Generated by `scripts/run_phase1.py` from the cached snapshot `{cfg.cache_path.relative_to(PROJECT_ROOT)}`.

## Data
- Source: {meta.get('source')} (yfinance {meta.get('yfinance_version')}), auto_adjust={meta.get('auto_adjust')}
- Downloaded (UTC): {meta.get('downloaded_at_utc')}; SHA-256 `{meta.get('sha256', '')[:16]}...`
- Requested range: {cfg.start} to {cfg.end} (inclusive)

## Data quality
{qrep.to_markdown()}

## Portfolio
- Weights: {cfg.weights} (constant, daily rebalanced); notional ${cfg.portfolio_value:,.0f}
- Return observations: {desc['observations']} ({port_r.index.min().date()} to {port_r.index.max().date()})
- Annualised vol: {desc['vol_annualised']:.2%}; skewness {desc['skewness']:.2f}; excess kurtosis {desc['excess_kurtosis']:.2f}
- Worst day: {desc['worst_day']:.2%} on {desc['worst_day_date']}; best day: {desc['best_day']:+.2%} on {desc['best_day_date']}

## Asset statistics (daily simple returns)
{asset_fmt.to_markdown()}

## 1-day VaR and ES (positive numbers are losses)
{fmt_tbl[['method', 'alpha', 'var', 'var_pct', 'es', 'es_pct', 'es_to_var', 'in_sample_exceed_rate']].to_markdown(index=False)}

Normal model uses sample mean: {cfg.normal_include_mean}. Historical quantile interpolation: `{cfg.quantile_method}`.

## Caveats
- Full-sample, in-sample estimates: every number above uses the whole 2006-2025 history,
  so they describe the past distribution; they are **not** forecasts and are not a backtest.
- Constant weights ignore rebalancing costs and weight drift.
- The in-sample exceedance rate of historical VaR is close to 1 - alpha by construction.
"""
    (out_dir / "phase1_report.md").write_text(report, encoding="utf-8")
    print(report)


if __name__ == "__main__":
    main()
